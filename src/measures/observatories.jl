"""
    observatory(name) -> MPosition{ITRF} | nothing

The ITRF position of a known telescope (`"VLA"`, `"ALMA"`, `"ATCA"`,
`"GBT"`, `"WSRT"`, `"GMRT"`, …), matched case-insensitively.  `nothing`
if the name is not in the bundled table.
"""
function observatory(name::AbstractString)
    xyz = get(_OBSERVATORIES, uppercase(strip(String(name))), nothing)
    xyz === nothing ? nothing : MPosition{ITRF}(xyz...)
end
